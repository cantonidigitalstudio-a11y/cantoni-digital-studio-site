  Object.keys(localePatches).forEach(function (lang) {
    translations[lang] = mergeLocale(translations.en, localePatches[lang]);
  });

  var ids = Object.keys(translations.en).filter(function (key) {
    return key !== 'lang' && key !== 'title';
  });

  function applyLanguage(lang) {
    var dict = translations[lang] || translations.en;
    document.documentElement.lang = dict.lang || 'en';
    document.title = dict.title || document.title;
    ids.forEach(function (id) {
      var node = document.getElementById(id);
      if (node && dict[id]) node.textContent = dict[id];
    });
    var occasionField = document.getElementById('guestOccasion');
    if (occasionField && dict.bookOccasionPlaceholder) {
      occasionField.setAttribute('placeholder', dict.bookOccasionPlaceholder);
    }
    picker.value = lang;
    localStorage.setItem('vip_lang', lang);
    if (window.ExcellentiaVipSeo && typeof window.ExcellentiaVipSeo.sync === 'function') {
      window.ExcellentiaVipSeo.sync();
    }
  }

  picker.addEventListener('change', function (event) {
    applyLanguage(event.target.value);
  });

  var queryLang = '';
  try {
    queryLang = new URLSearchParams(window.location.search).get('lang') || '';
  } catch {}
  var saved = queryLang || localStorage.getItem('vip_lang');
  applyLanguage(translations[saved] ? saved : 'en');
